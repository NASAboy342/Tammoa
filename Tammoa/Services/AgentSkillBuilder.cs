using System.Text;
using Tammoa.Models;

namespace Tammoa.Services;

/// <summary>Builds the skill the app serves: the hand-written file plus the parts that must never go stale because they come from the code.</summary>
public static class AgentSkillBuilder
{
    public static string Render(string template, string apiUrl, IReadOnlyList<AgentRoute> routes, IReadOnlyList<CardTypeInfo> cards)
    {
        var sb = new StringBuilder(template.TrimEnd());
        sb.Append("\n\n---\n\n## This Tammoa (generated by the running app)\n\n");
        sb.Append($"Base URL: `{apiUrl}`. Send `Authorization: Bearer <token>` on every request (the user gives you the token).\n\n");
        sb.Append("### Routes you may call\n\n| Method | Path | What it does |\n|---|---|---|\n");
        foreach (var r in routes)
            sb.Append($"| {r.Method} | `{r.Pattern}` | {r.Summary.Replace("|", "\\|")}{(r.NeedsRunPermission ? " **Only when the user switched on \"Let the agent run flows\"; otherwise 403. Ask the user before you run anything.**" : "")} |\n");
        sb.Append("\nAnything else answers 403.\n\n### Card types\n\nThe same list, live, is `GET /api/cards/types` (it also has a guide with examples per card). A card in a flow is `{ \"id\", \"type\", \"name\", \"position\": {\"x\",\"y\"}, \"params\": { … } }`.\n\n");
        foreach (var c in cards) AppendCard(sb, c);
        return sb.ToString();
    }

    private static void AppendCard(StringBuilder sb, CardTypeInfo c)
    {
        sb.Append($"#### {c.Name} — `{c.Type}`\n\n{c.Description}{(c.IsTrigger ? " (a trigger: it starts a flow)" : "")}{(c.IsSource ? " (runs at the start of a run, without a connection)" : "")}\n\n");
        if (c.Outputs.Count > 1 || c.Outputs[0].Key != "main") sb.Append($"Outputs (use as `sourceHandle` of a connection): {string.Join(", ", c.Outputs.Select(o => $"`{o.Key}`"))}\n\n");
        if (c.Guide?.Overview is { Length: > 0 } overview) sb.Append(overview.Trim()).Append("\n\n");
        if (c.Params.Count == 0) { sb.Append("No parameters.\n\n"); return; }
        sb.Append("Parameters:\n");
        foreach (var p in c.Params)
        {
            var parts = new List<string> { p.Kind.ToString() };
            if (p.Required) parts.Add("required");
            if (p.DefaultValue is { } d) parts.Add($"default {d.ToString(Newtonsoft.Json.Formatting.None)}");
            sb.Append($"- `{p.Key}` ({string.Join(", ", parts)}) {p.Label}");
            if (p.Options is { Count: > 0 }) sb.Append($". Values: {string.Join(", ", p.Options.Select(o => $"`{o.Value}`"))}");
            if (p.OptionsSource is { } src) sb.Append($". Values from `/api/cards/options/{src}`");
            if (!string.IsNullOrWhiteSpace(p.Help)) sb.Append($". {p.Help.Trim()}");
            sb.Append('\n');
        }
        sb.Append('\n');
    }
}
